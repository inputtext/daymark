import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=read('src/App.jsx')
const notes=read('src/components/NotesWorkspace.jsx')
const calendar=read('src/components/ExpressiveCalendar.jsx')
const css=read('src/native-clean.css')

test('native Android, not mobile viewport width, controls app-only cleanup',()=>{
  assert.match(app,/const NATIVE_ANDROID_APP = Capacitor\.isNativePlatform\(\) && Capacitor\.getPlatform\(\) === 'android'/)
  assert.ok(app.includes("NATIVE_ANDROID_APP?' native-app':''"))
  assert.match(css,/\.app-shell\.native-app/)
  assert.doesNotMatch(css,/\.app-shell(?::not\(|\s+\.topbar\s*\{)/)
  assert.match(read('src/main.jsx'),/import '\.\/native-clean\.css'/)
})
test('productivity shortcuts and keyboard badges exist only in desktop/browser build',()=>{
  assert.match(app,/if \(NATIVE_ANDROID_APP\) return undefined[\s\S]*?window\.addEventListener\('keydown', onKey\)/)
  assert.match(app,/e\.metaKey \|\| e\.ctrlKey/)
  assert.match(app,/e\.key\.toLowerCase\(\) === 'k'/)
  assert.match(app,/e\.key\.toLowerCase\(\) === 'n'/)
  assert.match(app,/e\.key\.toLowerCase\(\) === 'q'/)
  assert.match(app,/!NATIVE_ANDROID_APP&&<kbd>⌘ K<\/kbd>/)
  assert.match(app,/!NATIVE_ANDROID_APP&&<div><Keyboard size=\{16\}/)
  assert.match(app,/!NATIVE_ANDROID_APP&&<span className="breadcrumb">/)
})
test('Android task views prefer clear navigation/search over promotional captions',()=>{
  assert.match(app,/!NATIVE_ANDROID_APP&&<div className="eyebrow page-eyebrow"/)
  assert.ok(app.includes("NATIVE_ANDROID_APP?' native-app':''"))
  assert.match(app,/!NATIVE_ANDROID_APP&&<p>\{TITLES\[view\]\[1\]\}<\/p>/)
  assert.match(app,/!NATIVE_ANDROID_APP&&<button className="button-primary heading-add"/)
  assert.match(app,/\(!NATIVE_ANDROID_APP\|\|view==='inbox'\)/)
  assert.match(app,/native-gesture-help/)
  assert.match(app,/Swipe right to complete/)
  assert.match(css,/\.app-shell\.native-app \.task-panel\{order:1/)
  assert.match(css,/\.app-shell\.native-app \.hero-row\{order:2/)
})
test('native Notes and Calendar keep functional titles and explanatory text available on demand',()=>{
  assert.match(app,/NotesWorkspace nativeApp=\{NATIVE_ANDROID_APP\}/)
  assert.match(app,/ExpressiveCalendar nativeApp=\{NATIVE_ANDROID_APP\}/)
  assert.match(notes,/nativeApp\?'Notes':'A place for every little thought\.'/)
  assert.match(notes,/!nativeApp&&<span className="notes-eyebrow"/)
  assert.match(notes,/cloudMode\?nativeApp\?'Changes saved on this device/)
  assert.match(notes,/notes-cloud-banner/)
  assert.match(calendar,/!nativeApp&&<span className="daymark-calendar-eyebrow"/)
  assert.match(calendar,/native-calendar-help/)
  assert.match(calendar,/Move date to reschedule/)
  assert.match(css,/\.app-shell\.native-app \.page-heading\.is-detail-page\{display:none\}/)
})
test('native UI never removes account actions, accessibility or important system feedback',()=>{
  assert.match(app,/className="sidebar-footer"/)
  assert.match(app,/onClick=\{signOut\}/)
  assert.match(app,/Daymark is locked/)
  assert.match(app,/className="daymark-offline-tasks"/)
  assert.match(app,/className="modal v04-modal"/)
  assert.match(app,/role="status" className="toast/)
  assert.ok(app.includes('setLessMotion(value=>!value)'))
  assert.match(app,/Touch feedback follows your Android vibration settings/)
  assert.match(css,/Never hide forms, error messages, offline warnings/)
})
