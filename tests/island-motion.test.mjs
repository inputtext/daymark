import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {ISLAND_MOTION_PRESETS,validateIslandMotionStyle,islandStatus,syncIslandReducedMotion} from '../src/lib/island.js'
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('four distinctive motion profiles with explicit input validation',()=>{
  assert.deepEqual(ISLAND_MOTION_PRESETS.map(({id})=>id),['spring','bloom','elastic','glide'])
  for (const {id} of ISLAND_MOTION_PRESETS) assert.equal(validateIslandMotionStyle(id),id)
  for (const id of ['','off','bloom; DROP TABLE','pixel',undefined,null])
    assert.throws(()=>validateIslandMotionStyle(id))
})
test('native bridge provides style selection and reduced-motion sync without browser permissions',async()=>{
  const island=source('src/lib/island.js')
  assert.match(island,/DaymarkIsland\.setMotionStyle\(\{style:validateIslandMotionStyle\(style\)\}\)/)
  assert.match(island,/DaymarkIsland\.syncReducedMotion\(\{reduced:Boolean\(reduced\)\}\)/)
  const status=await islandStatus()
  assert.equal(status.motionStyle,'spring')
  assert.equal(status.motionReduced,false)
  assert.equal(await syncIslandReducedMotion(true),undefined)
})
test('island animation styles persist on device and never modify alarm scheduling',()=>{
  const prefs=source('android/app/src/main/java/com/piyush/daymark/IslandReminders.java')
  const plugin=source('android/app/src/main/java/com/piyush/daymark/DaymarkIslandPlugin.java')
  assert.match(prefs,/prefs\(context\)\.edit\(\)\.putString\("motionStyle"/)
  assert.match(prefs,/prefs\(context\)\.edit\(\)\.putBoolean\("motionReduced"/)
  assert.match(plugin,/state\.put\("motionStyle"/)
  assert.match(plugin,/state\.put\("motionReduced"/)
  assert.match(plugin,/@PluginMethod public void setMotionStyle/)
  assert.match(plugin,/@PluginMethod public void syncReducedMotion/)
  assert.match(prefs,/manager\.setAndAllowWhileIdle\(AlarmManager\.RTC_WAKEUP, at, operation\)/)
  assert.match(prefs,/static boolean notifyDue\(/)
})
test('native physics spring and lifecycle use cancellable Android animators',()=>{
  const motion=source('android/app/src/main/java/com/piyush/daymark/IslandMotion.java')
  const service=source('android/app/src/main/java/com/piyush/daymark/DaymarkIslandService.java')
  for(const id of ['SPRING','BLOOM','ELASTIC','GLIDE']) assert.match(motion,new RegExp('static final String '+id))
  assert.match(motion,/Math\.exp\(-z\*w\*t\)/)
  assert.match(motion,/ValueAnimator\.areAnimatorsEnabled\(\)/)
  assert.match(motion,/IslandReminders\.motionReduced\(context\)/)
  for(const id of ['animateEntrance','animateMorph','animateExit','measureDetails','detailsHeight','scheduleTimeout','removeOverlay','touchFeedback','snooze','openDaymark'])
    assert.match(service,new RegExp('private .*'+id+'\\('))
  assert.match(service,/morphAnimator\.cancel\(\)/)
  assert.match(service,/entryAnimator\.cancel\(\)/)
  assert.match(service,/exitAnimator\.cancel\(\)/)
  assert.match(service,/onAnimationCancel\(Animator animation\)/)
  assert.match(service,/View\.GONE/)
})
test('UI exposes style presets and keeps Android preview permission-gated',()=>{
  const ui=source('src/components/IslandSettings.jsx')
  const app=source('src/App.jsx')
  assert.match(ui,/Floating Island motion style/)
  assert.match(ui,/ISLAND_MOTION_PRESETS\.map/)
  assert.match(ui,/aria-pressed=\{motionStyle===option\.id\}/)
  assert.match(ui,/Preview Island/)
  assert.match(ui,/disabled=\{!supported \|\| !enabled \|\| !status\?\.overlayGranted \|\| busy\}/)
  assert.match(app,/syncIslandReducedMotion\(lessMotion\)/)
  assert.match(app,/reducedMotion=\{lessMotion\}/)
})
